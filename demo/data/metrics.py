"""
metrics.py
----------
Every number CLUE displays, computed from the modeled data source.

The metric is **90-Day Customer Value**: the average value generated per
acquired user during their first 90 days after acquisition. It is observed
history, not a prediction.

Two time windows are involved and they are deliberately not merged:

  - the *reference acquisition period* decides which cohort months are in view;
  - the *90-day observation window* is measured from each user's own
    acquisition date, so a user acquired late in a month still gets ninety days
    of follow-up.

Filtering orders by calendar date instead would quietly understate the metric.

CLUE explains **one cohort month**: the most recent month in the reference
period, which is the same month the baseline dashboard's KPI cards report. The
period arrives on the handoff link, so a participant who changed the dashboard's
filter and then clicked through sees the cohort they were actually looking at
rather than a pinned default. Both apps apply the same rule for which month is
the headline, so the two can never disagree about it.

CLUE reads the same Parquet tables the dashboard does, but shares no code with
it -- the two apps stay import-independent.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
import streamlit as st

# ---------------------------------------------------------------------------
# Reference acquisition period and observation window
# ---------------------------------------------------------------------------
#
# Matches baseline_dashboard/components/filters.py, so a participant handed over
# by "Open in CLUE" without an explicit period sees the figures they just left.

DEFAULT_START = pd.Period("2024-01", freq="M")
DEFAULT_END = pd.Period("2024-06", freq="M")

# Day 0 is the acquisition day itself, so the window is day offsets 0..89. This
# is not three anniversary months, which is why the month-grain age-facts table
# cannot express it and is not read here.
WINDOW_DAYS = 90
WINDOW_LABEL = f"{WINDOW_DAYS}-Day"

# Query parameters the baseline dashboard puts on the handoff link.
START_PARAM = "start"
END_PARAM = "end"

_DEFAULT_MODELED_DIR = (
    Path(__file__).resolve().parents[2] / "baseline_dashboard" / "data" / "modeled"
)


def modeled_dir() -> Path:
    """Where the modeled Parquet tables live. Override with CLUE_MODELED_DIR."""
    override = os.environ.get("CLUE_MODELED_DIR")
    return Path(override) if override else _DEFAULT_MODELED_DIR


# ---------------------------------------------------------------------------
# Formatting
# ---------------------------------------------------------------------------

def money(value: float) -> str:
    return f"${value:,.2f}" if abs(value) < 1000 else f"${value:,.0f}"


def whole_money(value: float) -> str:
    return f"${value:,.0f}"


def percent(value: float) -> str:
    return f"{value:.1%}"


def count(value: float) -> str:
    return f"{value:,.0f}"


def decimal(value: float) -> str:
    return f"{value:,.1f}"


def md(text: str) -> str:
    """
    Escape a formatted value for st.markdown.

    Streamlit reads text between two `$` as LaTeX, so a line carrying two money
    values renders as maths with the markup showing through. Escaping the
    dollar signs is the fix; HTML blocks are unaffected and do not need this.
    """
    return text.replace("$", r"\$")


def period_label(start: pd.Period, end: pd.Period) -> str:
    """Human-readable acquisition period, e.g. 'Jan-Jun 2024'."""
    if start == end:
        return start.strftime("%b %Y")
    if start.year == end.year:
        return f"{start.strftime('%b')}-{end.strftime('%b %Y')}"
    return f"{start.strftime('%b %Y')}-{end.strftime('%b %Y')}"


# ---------------------------------------------------------------------------
# The reference period, from the handoff link
# ---------------------------------------------------------------------------

def _parse_month(raw: str | None) -> pd.Period | None:
    """A YYYY-MM query parameter, or None when absent or unparseable."""
    if not raw:
        return None
    try:
        return pd.Period(str(raw), freq="M")
    except (ValueError, TypeError):
        return None


def reference_period(params=None) -> tuple[pd.Period, pd.Period]:
    """
    The acquisition period CLUE is explaining.

    Read from the handoff link, falling back to the dashboard's own default. A
    malformed or half-supplied parameter falls back rather than erroring: the
    link is generated by another app, and a study session should not die on a
    bad URL.
    """
    if params is None:
        try:
            params = st.query_params
        except Exception:  # no Streamlit runtime, e.g. a shell check
            params = {}

    start = _parse_month(params.get(START_PARAM))
    end = _parse_month(params.get(END_PARAM))
    if start is None or end is None:
        return DEFAULT_START, DEFAULT_END
    return (end, start) if start > end else (start, end)


# How far ahead the simulator plans, in months after the cohort being
# explained. The planning goal is worded "over the next 3 months".
FUTURE_MONTHS = 3


def future_window(cohort: pd.Period) -> tuple[pd.Period, pd.Period]:
    """The three acquisition months the simulator is planning for."""
    return cohort + 1, cohort + FUTURE_MONTHS


def _future_acquired_users(
    acquired_by_month: pd.Series, cohort: pd.Period
) -> tuple[int, str]:
    """
    How many users to assume are acquired over the next three months, and the
    label for where that number came from.

    Taken from the same three months a year earlier. Acquisition is seasonal,
    so last quarter's volume is a worse guide to next quarter than the same
    quarter last year is; it is also the only estimate here grounded in
    observed acquisition rather than in a rule of thumb.

    Falls back to repeating the cohort's own size when those months are not in
    the data, which keeps the simulator usable at the edges of the series
    rather than dividing a pathway by zero.
    """
    start, end = future_window(cohort)
    months = [month - 12 for month in pd.period_range(start, end, freq="M")]
    available = [month for month in months if month in acquired_by_month.index]

    if available:
        total = int(acquired_by_month.loc[available].sum())
        if total > 0:
            label = period_label(months[0], months[-1])
            return total, f"same three months a year earlier ({label})"

    cohort_size = int(acquired_by_month.get(cohort, 0))
    return (
        cohort_size * FUTURE_MONTHS,
        f"{FUTURE_MONTHS} x {cohort.strftime('%b %Y')} "
        f"(a year earlier is not in the data)",
    )


